"""A profile of the generated finance data, for a person to judge whether it looks real.

    python -m finance.report            # reads data/finance.duckdb, writes finance/data_profile.md

Uses the raw tables, the derived views and the as-at macros, so anything odd in
the report is either the data or the as-at logic, and both are worth knowing.
The _gen_ tables (each customer's hidden payer type) are used to show whether
the behaviours came out as intended; the semantic model will never see them.
"""

from __future__ import annotations

import argparse
from datetime import date
from pathlib import Path

import duckdb

from .generate import DEFAULT_OUT

OUT = Path(__file__).with_name("data_profile.md")
BUCKETS = ["Not yet due", "1-30 days", "31-60 days", "61-90 days", "Over 90 days", "Unapplied credit"]


def gbp(x) -> str:
    v = float(x or 0)
    return f"-£{-v:,.0f}" if v < 0 else f"£{v:,.0f}"


def long_date(d: date) -> str:
    return f"{d.day} {d:%B %Y}"


def pct(x) -> str:
    return f"{float(x or 0):.1%}"


def table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def build(con) -> str:
    q = lambda sql, *p: con.execute(sql, p).fetchall()
    info = dict(q("SELECT key, value FROM _gen_info"))
    today = date.fromisoformat(info["today"])
    sep = date(2026, 9, 30)
    s = [f"# Finance dataset profile\n",
         f"{info['company']} (fictitious). Today is {long_date(today)}; history from "
         f"{long_date(date.fromisoformat(info['history_start']))}. Seed {info['seed']}. Generated by "
         "`python -m finance.generate`; this report by `python -m finance.report`.\n",
         "Everything here is invented. The questions to ask of it: does it look like a real distributor's "
         "ledger, and would the finance team believe it?\n"]

    # ---- volumes
    counts = {t: q(f"SELECT COUNT(*) FROM {t}")[0][0] for t in ("OINV", "INV1", "ORIN", "ORCT", "RCT2")}
    cust = q("SELECT COUNT(*) FILTER (WHERE CardType = 'C'), COUNT(*) FILTER (WHERE CardType = 'S') FROM OCRD")[0]
    s.append("## Volumes\n")
    s.append(table(["What", "Rows"], [
        ["Customers (OCRD, C)", f"{cust[0]:,}"], ["Suppliers (OCRD, S; no documents until the AP stage)", f"{cust[1]:,}"],
        ["A/R invoices (OINV)", f"{counts['OINV']:,}"], ["Invoice lines (INV1)", f"{counts['INV1']:,}"],
        ["Credit notes (ORIN)", f"{counts['ORIN']:,}"], ["Incoming payments (ORCT)", f"{counts['ORCT']:,}"],
        ["Payment allocations (RCT2)", f"{counts['RCT2']:,}"]]))

    # ---- sales
    s.append("\n## Sales by year\n")
    s.append("Net of VAT and of credit notes. 2023 is November and December only; 2026 is January to October.\n")
    rows = q("""SELECT YEAR(document_date), SUM(net_amount) FILTER (WHERE document_type = 'Invoice'),
                       -SUM(net_amount) FILTER (WHERE document_type = 'Credit note'), SUM(net_amount),
                       COUNT(DISTINCT document_entry) FILTER (WHERE document_type = 'Invoice')
                FROM ar_sales_line GROUP BY 1 ORDER BY 1""")
    s.append(table(["Year", "Invoiced", "Credited", "Net sales", "Invoices"],
                   [[y, gbp(a), gbp(b), gbp(c), f"{n:,}"] for y, a, b, c, n in rows]))
    rows = q("""SELECT MONTH(document_date), SUM(net_amount) / COUNT(DISTINCT YEAR(document_date))
                FROM ar_sales_line WHERE document_date >= DATE '2024-01-01' AND document_date < DATE '2026-01-01'
                GROUP BY 1 ORDER BY 1""")
    avg = sum(float(v) for _, v in rows) / 12
    s.append("\nSeasonality, average net sales per calendar month over 2024 and 2025, against the monthly average:\n")
    s.append(table(["Month"] + [date(2025, m, 1).strftime("%b") for m, _ in rows],
                   [["Index"] + [f"{float(v) / avg:.2f}" for _, v in rows]]))
    rows = q("""SELECT c.customer_group, COUNT(DISTINCT c.customer_code), SUM(l.net_amount)
                FROM ar_sales_line l JOIN ar_customer c USING (customer_code)
                WHERE l.document_date >= DATE '2025-11-01' GROUP BY 1 ORDER BY 3 DESC""")
    s.append("\nLast 12 months by customer group:\n")
    s.append(table(["Group", "Customers", "Net sales"], [[g, n, gbp(v)] for g, n, v in rows]))
    rows = q("""SELECT g.ItmsGrpNam, SUM(l.LineTotal) FROM INV1 l JOIN OINV h USING (DocEntry) JOIN OITM i USING (ItemCode)
                JOIN OITB g USING (ItmsGrpCod) WHERE h.DocDate >= DATE '2025-11-01' GROUP BY 1 ORDER BY 2 DESC""")
    s.append("\nLast 12 months invoiced by item group:\n")
    s.append(table(["Item group", "Invoiced (net)"], [[g, gbp(v)] for g, v in rows]))

    # ---- aged debt
    s.append("\n## Aged debt\n")
    s.append("Rebuilt from dated documents, allocations and reconciliations by `ar_open_items(as_of)`, by days past the "
             "due date. Unapplied credits are standalone credit notes not yet matched to an invoice, shown negative.\n")
    for d in (today, sep):
        rows = dict(q("SELECT ageing_bucket, SUM(open_amount) FROM ar_open_items(CAST(? AS DATE)) GROUP BY 1", d))
        total = sum(float(v) for v in rows.values())
        unalloc = q("SELECT COALESCE(SUM(unallocated), 0) FROM ar_unallocated(CAST(? AS DATE))", d)[0][0]
        bal = q("SELECT SUM(balance) FROM ar_balance(CAST(? AS DATE))", d)[0][0]
        s.append(f"\nAs at {long_date(d)}:\n")
        s.append(table(["Bucket", "Open", "Share"], [[b, gbp(rows.get(b)), pct(float(rows.get(b, 0)) / total)] for b in BUCKETS]
                       + [["Net open items", gbp(total), ""], ["Less cash on account", gbp(unalloc), ""],
                          ["**Balance owed (ties to the ledger)**", f"**{gbp(bal)}**", ""]]))
    rows = q("""SELECT c.customer_name, c.customer_group, c.payment_terms, a.open_invoices, a.over_90,
                       a.days_61_90 + 0, g.payer_type
                FROM ar_aged_debt(CAST(? AS DATE)) a JOIN ar_customer c USING (customer_code)
                JOIN _gen_customer g ON g.CardCode = a.customer_code
                ORDER BY a.open_invoices DESC LIMIT 10""", today)
    s.append(f"\nTop ten customers by amount owed, as at {long_date(today)}. The last column is the hidden payer type, "
             "shown here only to judge the data:\n")
    s.append(table(["Customer", "Group", "Terms", "Owed", "Over 90 days", "61-90 days", "(payer type)"],
                   [[n, g, t, gbp(o), gbp(a), gbp(b), p] for n, g, t, o, a, b, p in rows]))

    # ---- DSO
    rows = []
    for m in range(5, 11):
        d = date(2026, m, 30 if m in (4, 6, 9, 11) else 31)
        bal = float(q("SELECT SUM(balance) FROM ar_balance(CAST(? AS DATE))", d)[0][0])
        sales = float(q("SELECT SUM(gross_amount) FROM ar_invoice WHERE invoice_date > CAST(? AS DATE) - 90 "
                        "AND invoice_date <= ?", d, d)[0][0])
        rows.append([f"{d:%d %b %Y}", gbp(bal), gbp(sales), f"{bal / sales * 90:.0f}"])
    rows_dso = rows
    s.append("\n## DSO\n")
    s.append("Proposed default definition: balance owed as at the date, divided by the last 90 days' invoiced sales "
             "including VAT, times 90.\n")
    s.append(table(["As at", "Balance", "Last 90 days invoiced", "DSO (days)"], rows))

    # ---- payment behaviour
    rows = q("""SELECT g.payer_type, COUNT(DISTINCT g.CardCode),
                       QUANTILE_CONT(DATE_DIFF('day', i.due_date, a.allocation_date), 0.1),
                       MEDIAN(DATE_DIFF('day', i.due_date, a.allocation_date)),
                       QUANTILE_CONT(DATE_DIFF('day', i.due_date, a.allocation_date), 0.9)
                FROM ar_allocation a JOIN ar_invoice i USING (invoice_entry) JOIN _gen_customer g ON g.CardCode = i.customer_code
                GROUP BY 1 ORDER BY 4""")
    s.append("\n## How customers pay\n")
    s.append("Days between the due date and the payment, by hidden payer type (negative is early):\n")
    s.append(table(["Payer type", "Customers", "10th percentile", "Median", "90th percentile"],
                   [[p, n, f"{a:.0f}", f"{b:.0f}", f"{c:.0f}"] for p, n, a, b, c in rows]))
    share = q("""WITH r AS (SELECT DocDate, DocTotal FROM ORCT),
                 last_wd AS (SELECT DISTINCT DocDate AS d FROM r WHERE DocDate = (
                     SELECT MAX(DocDate) FROM ORCT o WHERE DATE_TRUNC('month', o.DocDate) = DATE_TRUNC('month', r.DocDate)))
                 SELECT SUM(DocTotal) FILTER (WHERE DocDate IN (SELECT d FROM last_wd)) / SUM(DocTotal) FROM r""")[0][0]
    multi = q("SELECT AVG(n) FROM (SELECT COUNT(*) n FROM RCT2 GROUP BY DocNum)")[0][0]
    cn = q("""SELECT COUNT(*), SUM(c.net_amount), COUNT(*) FILTER (WHERE c.gross_amount = i.gross_amount),
                     COUNT(*) FILTER (WHERE c.standalone)
              FROM ar_credit_note c LEFT JOIN ar_invoice i USING (invoice_entry)""")[0]
    sales_total = q("SELECT SUM(net_amount) FROM ar_invoice")[0][0]
    on_acc = q("SELECT COUNT(*), SUM(NoDocSum) FROM ORCT WHERE NoDocSum > 0")[0]
    s.append("\n" + table(["Other behaviour", "Value"], [
        ["Share of cash received on the last working day of a month", pct(share)],
        ["Invoices settled per payment, on average", f"{float(multi):.1f}"],
        ["Credit notes", f"{cn[0]:,}, {gbp(cn[1])} net, {pct(float(cn[1]) / float(sales_total))} of invoiced sales"],
        ["Credit notes for the whole of the invoice they are based on", f"{cn[2]:,}"],
        ["Standalone credit notes (not based on an invoice)", f"{cn[3]:,} ({pct(cn[3] / cn[0])} of credit notes)"],
        ["Payments received on account rather than allocated", f"{on_acc[0]:,}, {gbp(on_acc[1])}"],
        ["Customers on stop (frozen)", q("SELECT COUNT(*) FROM OCRD WHERE frozenFor = 'Y'")[0][0]],
    ]))

    # ---- cancellations
    canc = q("SELECT COUNT(*), SUM(DocTotal) FROM OINV WHERE CANCELED = 'Y'")[0]
    s.append("\n## Cancelled invoices\n")
    s.append(f"{canc[0]:,} invoices ({gbp(canc[1])} including VAT) were cancelled, each with its B1 cancellation "
             "document (ORIN.CANCELED = C). Both halves are excluded from every view; the tests check each pair nets "
             "to zero and that nothing else ever touches a cancelled invoice. Summing OINV without the CANCELED filter "
             f"overstates sales by exactly that {gbp(canc[1])}.\n")

    # ---- the matching backlog
    s.append("\n## The matching backlog\n")
    s.append(f"Standalone credits and payments on account with something still to match, as at {long_date(today)}, "
             "by what the Comments field gives away (the quality is hidden ground truth from `_gen_match`):\n")
    rows = q("""WITH b AS (SELECT * FROM ar_matching_backlog(CAST(? AS DATE))),
                 q AS (SELECT DISTINCT source_type, source_entry, reference_quality FROM _gen_match)
                SELECT b.source_type,
                       CASE WHEN c.PaidToDate > 0 THEN 'residue after a match' ELSE 'not matched' END status,
                       COALESCE(q.reference_quality, 'unidentified cash') quality, COUNT(*), SUM(amount_to_match),
                       MEDIAN(DATE_DIFF('day', b.source_date, CAST(? AS DATE)))
                FROM b LEFT JOIN q ON q.source_entry = b.source_entry AND q.source_type = LOWER(b.source_type)
                LEFT JOIN ORIN c ON b.source_type = 'Credit note' AND c.DocEntry = b.source_entry
                GROUP BY 1, 2, 3 ORDER BY 1, 2, 4 DESC""", today, today)
    s.append(table(["Waiting", "Status", "Reference in Comments", "Items", "To match", "Median age (days)"],
                   [[t, st, ql, f"{n:,}", gbp(v), f"{a:.0f}"] for t, st, ql, n, v, a in rows]))
    s.append("\nA residue is the part of a credit never assigned after the rest was matched (the £100 credit split "
             "40/30/10 leaves £20): it is old by nature and usually ends in a write-off or a refund.\n")
    hidden = q("""SELECT COUNT(DISTINCT o.document_entry), SUM(o.open_amount)
                  FROM _gen_match m JOIN ar_open_items(CAST(? AS DATE)) o
                    ON o.document_type = 'Invoice' AND o.document_entry = m.invoice_entry
                  WHERE (m.recon_date IS NULL OR m.recon_date > ?) AND o.days_overdue > 0""", today, today)[0]
    s.append(f"\nThe pain point in one number: {hidden[0]:,} invoices ({gbp(hidden[1])} open) look overdue today only "
             "because the credit or payment that clears them hasn't been matched.\n")
    rows = q("""SELECT b.source_type, b.source_number, b.source_date, b.amount_to_match, COALESCE(b.comments, ''),
                       q.reference_quality, q.invoices
                FROM ar_matching_backlog(CAST(? AS DATE)) b
                JOIN (SELECT source_type, source_entry, MAX(reference_quality) reference_quality,
                             STRING_AGG(i.DocNum::VARCHAR, ', ' ORDER BY i.DocNum) invoices
                      FROM _gen_match m JOIN OINV i ON i.DocEntry = m.invoice_entry GROUP BY 1, 2) q
                  ON q.source_entry = b.source_entry AND q.source_type = LOWER(b.source_type)
                ORDER BY HASH(b.source_entry) LIMIT 12""", today)
    s.append("\nA sample, with the true invoices the matcher should find (hidden from it):\n")
    s.append(table(["Waiting", "Number", "Date", "To match", "Comments", "(quality)", "(true invoices)"],
                   [[t, n, f"{d:%d %b %Y}", gbp(v), c.replace("|", "/") or "(blank)", ql, inv]
                    for t, n, d, v, c, ql, inv in rows]))
    multi = q("""SELECT COUNT(*) FILTER (WHERE n > 1), COUNT(*) FILTER (WHERE left_over > 0) FROM (
                   SELECT c.DocEntry, COUNT(m.invoice_entry) n, c.DocTotal - SUM(m.amount) left_over
                   FROM ORIN c JOIN _gen_match m ON m.source_type = 'credit note' AND m.source_entry = c.DocEntry
                   GROUP BY c.DocEntry, c.DocTotal)""")[0]
    recon = q("SELECT COUNT(*), MEDIAN(n) FROM (SELECT ReconNum, COUNT(*) n FROM ITR1 GROUP BY 1)")[0]
    s.append("\n" + table(["Matching facts", "Value"], [
        ["Standalone credits covering more than one invoice", f"{multi[0]:,}"],
        ["Standalone credits with part never assigned (the £100 split 40/30/10)", f"{multi[1]:,}"],
        ["Internal reconciliations (OITR) made so far", f"{recon[0]:,}, median {recon[1]:.0f} documents each"],
    ]))

    # ---- CIS
    cis = q("""SELECT COUNT(*) FILTER (WHERE CardType = 'S' AND WTLiable = 'Y'),
                      COUNT(*) FILTER (WHERE CardType = 'S' AND WTCode = 'CIS0'),
                      COUNT(*) FILTER (WHERE CardType = 'S' AND WTCode = 'CIS20'),
                      COUNT(*) FILTER (WHERE CardType = 'S' AND WTCode = 'CIS30'),
                      COUNT(*) FILTER (WHERE CardType = 'C' AND U_CIS_Contractor = 'Y'),
                      COUNT(*) FILTER (WHERE CardType = 'C')
               FROM OCRD""")[0]
    s.append("\n## CIS and withholding tax\n")
    s.append(f"{cis[0]} suppliers are subcontractors subject to withholding tax (OCRD.WTLiable = Y): {cis[1]} with gross "
             f"payment status (CIS0), {cis[2]} registered (CIS20) and {cis[3]} unregistered (CIS30). Deductions on what "
             f"we pay them arrive with the AP stage. {cis[4]} of {cis[5]} customers are flagged as CIS-registered "
             "contractors (U_CIS_Contractor, a user-defined field); CIS doesn't apply to the goods we sell them.\n")

    # ---- one customer's story
    code = q("""SELECT g.CardCode FROM _gen_customer g JOIN ar_aged_debt(CAST(? AS DATE)) a ON a.customer_code = g.CardCode
                WHERE g.payer_type = 'chronic' ORDER BY a.over_90 DESC NULLS LAST LIMIT 1""", today)[0][0]
    c = q("SELECT customer_name, payment_terms FROM ar_customer WHERE customer_code = ?", code)[0]
    rows = q("""SELECT movement_date, movement_type, document_entry, amount,
                       SUM(amount) OVER (ORDER BY movement_date, movement_type, document_entry) AS running
                FROM ar_ledger WHERE customer_code = ? ORDER BY movement_date, movement_type, document_entry""", code)
    s.append(f"\n## One account: {c[0]} ({code}), a chronic late payer on {c[1]}\n")
    s.append("The last 20 movements on the account, with the running balance:\n")
    s.append(table(["Date", "Movement", "Document", "Amount", "Balance"],
                   [[f"{d:%d %b %Y}", t, e, gbp(a), gbp(r)] for d, t, e, a, r in rows[-20:]]))

    # ---- prompts for the reviewer, from the figures above
    per_year = q("SELECT COUNT(*), SUM(net_amount) FROM ar_invoice WHERE invoice_date > DATE '2025-10-31'")[0]
    mix = dict(q("SELECT payer_type, COUNT(*) FROM _gen_customer GROUP BY 1"))
    aged = dict(q("SELECT ageing_bucket, SUM(open_amount) FROM ar_open_items(CAST(? AS DATE)) GROUP BY 1", today))
    aged_total = sum(float(v) for v in aged.values())
    dso = [float(r[3]) for r in rows_dso]
    s.append("\n## Judgement calls to review\n")
    s.append(f"- **Volumes:** {per_year[0]:,} invoices and {gbp(per_year[1])} invoiced (excluding VAT) in the last 12 months, "
             f"from {cust[0]} customers. Right size for the story?\n"
             f"- **Payer mix:** {mix.get('prompt', 0)} prompt, {mix.get('slow', 0)} slow, {mix.get('batch', 0)} batch, "
             f"{mix.get('chronic', 0)} chronic, {mix.get('disputes', 0)} disputes, {mix.get('partial', 0)} partial and "
             f"{mix.get('bad_debt', 0)} bad debts.\n"
             f"- **Ageing today:** {pct(float(aged.get('Not yet due', 0)) / aged_total)} not yet due and "
             f"{pct(float(aged.get('Over 90 days', 0)) / aged_total)} over 90 days. Does it look like a real aged debt report? "
             "The 1-30 day bucket swings between month-ends because end-of-month terms fall due together.\n"
             f"- **DSO** between {min(dso):.0f} and {max(dso):.0f} days on mostly 30-day and end-of-month terms. "
             "Plausible for your customers?\n"
             f"- **Top debtors:** six key accounts dominate the top of every list by design.\n"
             "- **No bank holidays:** working days are Monday to Friday only.\n"
             "- **Credit notes:** about a third are standalone and matched later, sometimes across several invoices, sometimes "
             "with part left over. Customers short-pay invoices they expect a credit against. Is that how it happens at RSIS?\n"
             "- **References:** 45% clean, 20% mistyped, 15% our customer's PO, 20% nothing. Does that match your backlog?\n"
             "- **Reconciliation lag:** a credit with a clean reference is matched within about 2 to 40 working days, and "
             "1% never; with no reference it takes three times as long and a fifth are never matched. Realistic?\n"
             "- **Payments on account:** 3% of payments arrive unallocated and are reconciled within 30 working days, or not.\n"
             "- Every number above comes from `finance/generator.yaml`: change a share, regenerate, rerun the tests.\n")
    return "\n".join(s)


def main() -> int:
    parser = argparse.ArgumentParser(prog="python -m finance.report")
    parser.add_argument("--db", default=str(DEFAULT_OUT))
    parser.add_argument("--out", default=str(OUT))
    args = parser.parse_args()
    con = duckdb.connect(args.db, read_only=True)
    text = build(con)
    con.close()
    Path(args.out).write_text(text, encoding="utf-8")
    print(f"Written {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
